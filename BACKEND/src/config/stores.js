const normalizeText = (text) => {
  return String(text || '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toUpperCase()
    .trim();
};

export const findStore = (input) => {
  if (!input) return null;
  const raw = String(input).trim();
  if (!raw) return null;

  const clean = normalizeText(raw);
  const cleanNoLP = clean.replace(/^LP\s*[-_]?\s*/i, '').trim();
  const tokens = clean.split(/[\s\-_/\\,;:|]+/).filter(Boolean);

  // 1. Correspondência exata direta (ID interno, CODE ID, SAP, NOME ou ALIAS)
  let found = STORES.find(store => {
    const sId = normalizeText(store.id);
    const sCode = normalizeText(store.code);
    const sSap = normalizeText(store.sap);
    const sName = normalizeText(store.name);
    const sNameNoLP = sName.replace(/^LP\s*[-_]?\s*/i, '').trim();

    if (sId === clean || sId === cleanNoLP) return true;
    if (sCode === clean || sCode === cleanNoLP) return true;
    if (sSap && (sSap === clean || sSap === cleanNoLP)) return true;
    if (sName === clean || sNameNoLP === cleanNoLP) return true;

    if (Array.isArray(store.aliases)) {
      return store.aliases.some(alias => {
        const aNorm = normalizeText(alias);
        return aNorm === clean || aNorm === cleanNoLP;
      });
    }
    return false;
  });

  if (found) return found;

  // 2. Busca por tokens/palavras (ex: "K7W8 RAPOSO", "1146 RAPOSO", "RAPOSO 1146", "K7W8 1146", "LB31 MORUMBI")
  // Verifica se algum token bate exatamente com CODE ou SAP
  const matchedByTokens = STORES.filter(store => {
    const sCode = normalizeText(store.code);
    const sSap = normalizeText(store.sap);
    return tokens.some(token => token === sCode || (sSap && token === sSap));
  });

  if (matchedByTokens.length === 1) {
    return matchedByTokens[0];
  } else if (matchedByTokens.length > 1) {
    // Se digitou dois códigos diferentes de lojas distintas, retorna null por segurança
    return null;
  }

  // 3. Busca por nome/alias contido quando maior ou igual a 3 caracteres
  found = STORES.find(store => {
    const sName = normalizeText(store.name);
    const sNameNoLP = sName.replace(/^LP\s*[-_]?\s*/i, '').trim();
    const sId = normalizeText(store.id);

    if (cleanNoLP.length >= 4 && (sNameNoLP === cleanNoLP || sId === cleanNoLP)) return true;

    if (Array.isArray(store.aliases)) {
      return store.aliases.some(alias => {
        const aNorm = normalizeText(alias);
        return aNorm.length >= 4 && aNorm === cleanNoLP;
      });
    }
    return false;
  });

  if (found) return found;

  // 4. Substring parcial segura (prioriza match mais específico)
  const partialMatches = STORES.filter(store => {
    if (store.id === 'DEFAULT') return false;
    const sNameNoLP = normalizeText(store.name).replace(/^LP\s*[-_]?\s*/i, '').trim();
    const sId = normalizeText(store.id);

    if (cleanNoLP.length >= 4 && (sNameNoLP.includes(cleanNoLP) || cleanNoLP.includes(sNameNoLP))) return true;
    if (cleanNoLP.length >= 4 && sId.includes(cleanNoLP)) return true;

    if (Array.isArray(store.aliases)) {
      return store.aliases.some(alias => {
        const aNorm = normalizeText(alias);
        return aNorm.length >= 4 && (cleanNoLP.includes(aNorm) || aNorm.includes(cleanNoLP));
      });
    }
    return false;
  });

  if (partialMatches.length === 1) {
    return partialMatches[0];
  }

  return null;
};

export const getStoreById = (id) => findStore(id) || STORES[1];
